def fix_text(value):
    """Apply Georgian corrections to a single value. Non-strings pass through."""
    if not isinstance(value, str):
        return value
    fixed = value
    for old, new in REPLACEMENTS:
        if old in fixed:
            fixed = fixed.replace(old, new)
    return fixed
